"""Human-readable load comparison for an independently validated draft."""
import json
import sys
from pathlib import Path

p=Path(sys.argv[1])
r=json.loads((p/'final-validation.json').read_text(encoding='utf-8'))
x=json.loads((p/'excel-validation.json').read_text(encoding='utf-8'))
assert r['ok'] and x['ok']
data=json.loads((p/'base-data.json').read_text(encoding='utf-8'))
previous={t['teacher']:t['pairs'] for t in data['settings'].get('preserve_teacher_period_loads',data['settings'].get('preferred_teacher_period_loads',[]))}
lines=['# Расписание 18–19 сентября 2026', '',
       f"Всего {r['total_pairs']} пар: {r['pairs_by_date']['2026-09-18']} в пятницу, {r['pairs_by_date']['2026-09-19']} в субботу.", '',
       'Каждая физическая подгруппа: ровно четыре пары в день, без окон. Пересечений у преподавателей нет. Общие занятия записаны в Excel только в верхнюю ячейку. Дни дистанта выделены зелёным.', '',
       'Усиленные и индивидуально заданные нагрузки сохранены. По согласованию с пользователем у остальных преподавателей разрешено перераспределение. Дополнительная нагрузка не превышает остатки часов с учётом ранее запланированных занятий.', '',
       'Михайловой Татьяне поставлены пары 1–5 в пятницу; суббота оставлена выходной согласно прежнему рабочему графику. Кругловой запрещены пары 6–7 в оба дня.', '',
       'Тарасов и Садриева исключены из обоих дней. Ахметов: остаток 540 часов, из них 138 часов нужно завершить до 8 ноября; назначено 7+7. Новосёлова — пятница 1–4, Коробкова — 4+4, Буркова и Ханьжина — 7 в субботу. Цимфер и Кропотова — по 2–3 пары ежедневно. Кабинеты указаны справочно: закреплённые либо привычные по журналу; их занятость не ограничивает дистанционные занятия.', '',
       'У Третяк после выполнения этого проекта останутся две пары общей теории. Подгрупповые занятия информатики учитываются отдельно.', '',
       '## Нагрузка преподавателей', '',
       '| Преподаватель | Пятница | Суббота | Всего | Было за два дня |',
       '|---|---:|---:|---:|---:|']
for t in r['teacher_loads']:
    old=previous.get(t['teacher_id'],0)
    lines.append(f"| {t['name']} | {t['friday']} | {t['saturday']} | {t['total']} | {old} |")
lines += ['', '## Рабенок Мария Александровна: все 11 групп по одному разу', '',
          '| Группа | Дата | Пара |','|---|---|---:|']
for g in sorted(r['rabenok_groups'],key=lambda g:(g['date'],g['slot'])):
    lines.append(f"| {g['group']} | {g['date']} | {g['slot']} |")
lines += ['', 'Проверено независимо от решателя: исходные остатки часов, резервы, доступность, дедлайны групп, блоки ЛПЗ, отсутствие окон и пересечений, сохранение нагрузки и все ячейки сохранённого Excel. Это проект будущих занятий; в проведённые часы он не записан.', '']
(p/'Нагрузка_и_проверка.md').write_text('\n'.join(lines),encoding='utf-8')
print(f"Validated {r['total_pairs']} pairs, {len(r['teacher_loads'])} teachers, {len(r['rabenok_groups'])} Rabenok groups")
